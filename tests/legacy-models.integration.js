"use strict";
const assert=require("node:assert/strict"),crypto=require("node:crypto");
module.exports=async function verifyModels({db,company,other,actor}) {
    const customers=require("../models/clienteModel"),pets=require("../models/petModel"),products=require("../models/produtoModel"),suppliers=require("../models/fornecedorModel");
    const code=crypto.randomUUID();
    const customer=await customers.create({empresaId:other,nome:"Titular isolado",email:code+"@example.test",telefone:"11970000001"});
    assert.equal(customer.empresa_id,other);
    assert.equal(await customers.findById(customer.id,company),null);
    assert.ok(!(await customers.findAll(company)).some(item=>item.id===customer.id));
    await assert.rejects(customers.update(customer.id,{nome:"Ataque"},company),{status:404});
    await assert.rejects(customers.remove(customer.id,company),{status:404});
    const supplier=await suppliers.criar({empresa_id:other,nome:"Fornecedor isolado",cnpj:"MODEL-"+code.slice(0,8)});
    assert.equal(supplier.empresa_id,other);
    assert.equal(await suppliers.buscarPorId(supplier.id,company),undefined);
    assert.equal(await suppliers.excluir(supplier.id,company),undefined);
    assert.ok(!(await suppliers.listar(company)).some(item=>item.id===supplier.id));
    const category=(await db.query("INSERT INTO categorias(empresa_id,nome) VALUES($1,'Categoria isolada') RETURNING id",[other])).rows[0].id;
    const payload={empresaId:other,categoriaId:category,fornecedor_id:supplier.id,nome:"Produto isolado",sku:code,preco:"30.50",custo:"10.00",marca:"Marca Teste",unidade_medida:"KG",estoque_minimo:4,foto:"https://res.cloudinary.com/test/image/upload/synthetic.png"};
    const product=await products.create(payload);
    assert.equal(product.empresa_id,other);assert.equal(Number(product.preco_venda),30.5);assert.equal(Number(product.preco_custo),10);
    assert.equal(product.marca,"Marca Teste");assert.equal(product.estoque_minimo,4);
    assert.equal(await products.findById(product.id,company),null);
    assert.ok(!(await products.findAll(company)).some(item=>item.id===product.id));
    await assert.rejects(products.update(product.id,payload,company),{status:404});
    await assert.rejects(products.remove(product.id,company),{status:404});
    await db.query("UPDATE estoque SET quantidade=5 WHERE produto_id=$1 AND empresa_id=$2",[product.id,other]);
    const updated=await products.update(product.id,{...payload,foto:undefined,preco:"40.00",custo:"12.00",estoque_minimo:2,status:false},other);
    assert.equal(updated.foto,product.foto);assert.equal(Number(updated.preco_venda),40);assert.equal(Number(updated.preco_custo),12);
    assert.equal(updated.status,false);assert.equal(updated.ativo,false);
    const stock=(await db.query("SELECT * FROM estoque WHERE produto_id=$1 AND empresa_id=$2",[product.id,other])).rows[0];
    assert.equal(stock.quantidade,5);assert.equal(stock.estoque_minimo,2);
    await products.remove(product.id,other);
    assert.ok(await products.findById(product.id,other));
    await assert.rejects(products.create({...payload,empresaId:company,sku:crypto.randomUUID()}),{status:400});
    await assert.rejects(db.query("INSERT INTO produtos(empresa_id,categoria_id,nome,preco) VALUES($1,$2,'Vínculo incorreto',20)",[company,category]),{code:"23503"});
    const pet=await pets.create({empresaId:other,clienteId:customer.id,nome:"Pet isolado",especie:"CACHORRO"});
    assert.equal(pet.empresa_id,other);assert.equal(await pets.findById(pet.id,company),null);
    assert.ok(!(await pets.findAll(company)).some(item=>item.id===pet.id));
    await assert.rejects(pets.create({empresaId:company,clienteId:customer.id,nome:"Pet inválido",especie:"CACHORRO"}),{status:400});
    await assert.rejects(pets.remove(pet.id,company),{status:404});
    const nextOwner=await customers.create({empresaId:other,nome:"Segundo titular",email:crypto.randomUUID()+"@example.test",telefone:"11970000002"});
    await db.query("INSERT INTO consultas(empresa_id,cliente_id,pet_id,data_consulta,horario,motivo_consulta) VALUES($1,$2,$3,CURRENT_DATE,'10:00','Histórico preservado')",[other,customer.id,pet.id]);
    await assert.rejects(pets.update(pet.id,{clienteId:nextOwner.id,nome:pet.nome,especie:pet.especie},other),{status:409});
    await pets.remove(pet.id,other);
    const removed=await pets.findById(pet.id,other);assert.equal(removed.ativo,false);assert.equal(removed.status,false);
    await suppliers.excluir(supplier.id,other);
    assert.equal((await suppliers.buscarPorId(supplier.id,other)).ativo,false);
    assert.ok(await products.findById(product.id,other));
};
